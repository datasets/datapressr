// Template: descriptive statistics for a structured dataset.
//
// Copy into the dataset directory as enrich.ts (next to build.ts). Reads
// datapackage.json (for field types) + each resource's CSV and rewrites only
// the fenced block in SUMMARY.md (between the STATS markers). Everything
// outside the fence — the title, the hand-written "What stands out" and
// "See also" sections — is left untouched. First run lays down the whole
// file from a template.
//
// One consolidated table, one row per resource + measurement column (the
// enrich skill's default). Standard deviation is the population statistic
// (denominator n, not n-1) and the table caption says so. An empty
// population (n = 0) produces blank cells rather than NaN or 0. Only an
// empty or unparseable cell counts as missing — zero and negative values
// are data.
//
// Assumes clean generated CSVs (no quoted fields, as a structure build
// writes them); for quoted CSV swap readCsv for a real parser.
//
// Run:  node enrich.ts    (Node 22+, native TS, no build step, no dependencies)
// Deterministic: same input -> byte-identical fenced block.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

export const BEGIN = "<!-- STATS:BEGIN — generated by enrich.ts, do not edit by hand -->";
export const END = "<!-- STATS:END -->";

type Field = { name: string; type: string; description?: string };
type Resource = { name: string; title: string; path: string; schema: { fields: Field[] } };
type Datapackage = { name: string; resources: Resource[] };

export function round(n: number, dp = 3): number {
  const f = 10 ** dp;
  return Math.round(n * f) / f;
}

export type NumStats = {
  n: number;
  missing: number;
  min: number | null;
  max: number | null;
  mean: number | null;
  median: number | null;
  stddev: number | null;
};

/**
 * Population statistics (denominator n) for a raw column of string values.
 * `missing` counts anything that isn't a finite number — an empty cell or
 * unparseable garbage alike — so `n + missing` always equals `raw.length`.
 */
export function numericStats(raw: string[]): NumStats {
  const xs = raw
    .map((v) => (v === "" || v === undefined || v === null ? NaN : Number(v)))
    .filter(Number.isFinite)
    .sort((a, b) => a - b);
  const n = xs.length;
  const missing = raw.length - n;
  if (n === 0) {
    return { n: 0, missing, min: null, max: null, mean: null, median: null, stddev: null };
  }
  const sum = xs.reduce((a, b) => a + b, 0);
  const mean = sum / n;
  const variance = xs.reduce((a, b) => a + (b - mean) ** 2, 0) / n;
  const median = n % 2 ? xs[(n - 1) / 2] : (xs[n / 2 - 1] + xs[n / 2]) / 2;
  return {
    n,
    missing,
    min: xs[0],
    max: xs[n - 1],
    mean: round(mean),
    median: round(median),
    stddev: round(Math.sqrt(variance)),
  };
}

/** Parse a clean generated CSV (no quoted fields) into row objects. */
export function readCsv(text: string): Record<string, string>[] {
  const [head, ...lines] = text.trim().split("\n");
  const cols = head.split(",");
  return lines.map((l) => Object.fromEntries(l.split(",").map((v, i) => [cols[i], v])));
}

const NUMERIC = new Set(["number", "integer"]);
// A number-typed column that encodes a point in time is an identifier, not a
// measurement — min/max/mean of it says nothing. Explicit key list, not
// substring matching: `mlo_ppm_per_year` contains "year" and is a real
// measurement.
const TIME_KEYS = new Set(["decimal_date", "date", "year", "month", "day", "decade"]);
export const isMeasurement = (f: Field): boolean =>
  NUMERIC.has(f.type) && !TIME_KEYS.has(f.name.toLowerCase()) && !f.name.toLowerCase().endsWith("_date");

/** Row count plus the range of the first date/year/string field. */
export function coverage(rows: Record<string, string>[], fields: Field[]): string {
  const key = fields.find((f) => ["date", "year", "string"].includes(f.type));
  if (!key) return "—";
  const vals = rows.map((r) => r[key.name]).filter(Boolean).sort();
  return vals.length ? `${vals[0]} → ${vals.at(-1)}` : "—";
}

function fmt(v: number | null): string {
  return v === null ? "" : String(v);
}

export function buildStatsBlock(pkg: Datapackage, readResource: (path: string) => string): string {
  const block: string[] = [
    BEGIN,
    "",
    "One row per resource + measurement. Standard deviation is the population statistic (denominator n).",
    "",
    "| resource | measurement | rows | coverage | n | missing | min | max | mean | median | std dev |",
    "|---|---|--:|---|--:|--:|--:|--:|--:|--:|--:|",
  ];
  for (const res of pkg.resources) {
    const rows = readCsv(readResource(res.path));
    const cov = coverage(rows, res.schema.fields);
    const numFields = res.schema.fields.filter(isMeasurement);
    if (numFields.length === 0) {
      block.push(`| \`${res.name}\` | _none_ | ${rows.length} | ${cov} | | | | | | | |`);
      continue;
    }
    for (const f of numFields) {
      const s = numericStats(rows.map((r) => r[f.name]));
      block.push(
        `| \`${res.name}\` | ${f.name} | ${rows.length} | ${cov} | ${s.n} | ${s.missing} | ${fmt(s.min)} | ${fmt(s.max)} | ${fmt(s.mean)} | ${fmt(s.median)} | ${fmt(s.stddev)} |`,
      );
    }
  }
  block.push(END);
  return block.join("\n");
}

export function spliceIntoSummary(existing: string | null, statsBlock: string, name: string): string {
  let doc: string;
  if (existing !== null) {
    const b = existing.indexOf(BEGIN);
    const e = existing.indexOf(END);
    if (b === -1 || e === -1) throw new Error("SUMMARY.md is missing the STATS markers");
    doc = existing.slice(0, b) + statsBlock + existing.slice(e + END.length);
  } else {
    doc = [
      `# Summary — ${name}`,
      "",
      "Descriptive statistics for every resource. The table block below is generated by [`enrich.ts`](enrich.ts) (`node enrich.ts`) and rewritten in place on each run; the prose around it is written by hand.",
      "",
      "## Statistics",
      "",
      statsBlock,
      "",
      "## What stands out",
      "",
      "_TODO — the handful of things a reader should take from the numbers above._",
      "",
      "## See also",
      "",
      "- _TODO — the story, the source, related datasets._",
      "",
    ].join("\n");
  }
  return doc.replace(/\n{3,}/g, "\n\n").replace(/\n*$/, "\n");
}

function isMain(): boolean {
  return process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
}

function main(): void {
  const HERE = dirname(fileURLToPath(import.meta.url));
  const pkg = JSON.parse(readFileSync(join(HERE, "datapackage.json"), "utf8")) as Datapackage;
  const statsBlock = buildStatsBlock(pkg, (path) => readFileSync(join(HERE, path), "utf8"));
  const summaryPath = join(HERE, "SUMMARY.md");
  const existing = existsSync(summaryPath) ? readFileSync(summaryPath, "utf8") : null;
  writeFileSync(summaryPath, spliceIntoSummary(existing, statsBlock, pkg.name));
  console.log(existing ? "updated SUMMARY.md stats block" : "wrote SUMMARY.md");
}

if (isMain()) main();
