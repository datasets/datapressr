// Enrich — descriptive statistics for the co2-ppm dataset.
//
// Reads the structured data/*.csv + datapackage.json (for field types) and
// rewrites only the fenced block in SUMMARY.md (between the STATS markers) with
// one stats table per resource plus a coverage line. Everything outside the
// fence — the title, the hand-written "What stands out" and "See also" — is
// left untouched. First run lays down the whole file from a template.
//
// Run:  node enrich.ts    (Node 22+, native TS, no build step, no dependencies)
// Deterministic: same input -> byte-identical fenced block.

const BEGIN = "<!-- STATS:BEGIN — generated by enrich.ts, do not edit by hand -->";
const END = "<!-- STATS:END -->";

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const DATA = join(HERE, "data");

type Field = { name: string; type: string; description?: string };
type Resource = { name: string; path: string; title: string; schema: { fields: Field[] } };

const pkg = JSON.parse(readFileSync(join(HERE, "datapackage.json"), "utf8")) as {
  resources: Resource[];
};

/** Parse a clean generated CSV (no quoted fields) into row objects. */
function readCsv(path: string): Record<string, string>[] {
  const [head, ...lines] = readFileSync(join(HERE, path), "utf8").trim().split("\n");
  const cols = head.split(",");
  return lines.map((l) => Object.fromEntries(l.split(",").map((v, i) => [cols[i], v])));
}

function round(n: number, dp = 2): number {
  const f = 10 ** dp;
  return Math.round(n * f) / f;
}

type NumStats = {
  field: string;
  n: number;
  missing: number;
  min: number;
  max: number;
  mean: number;
  median: number;
  stddev: number;
};

function numericStats(field: string, raw: string[]): NumStats {
  const present = raw.filter((v) => v !== "" && v !== undefined);
  const xs = present.map(Number).filter(Number.isFinite).sort((a, b) => a - b);
  const n = xs.length;
  const sum = xs.reduce((a, b) => a + b, 0);
  const mean = sum / n;
  const variance = xs.reduce((a, b) => a + (b - mean) ** 2, 0) / n;
  const median = n % 2 ? xs[(n - 1) / 2] : (xs[n / 2 - 1] + xs[n / 2]) / 2;
  return {
    field,
    n,
    missing: raw.length - present.length,
    min: xs[0],
    max: xs[n - 1],
    mean: round(mean, 3),
    median: round(median, 3),
    stddev: round(Math.sqrt(variance), 3),
  };
}

/** Coverage: the range of the first date/year/string field, plus row count. */
function coverage(rows: Record<string, string>[], fields: Field[]): string {
  const key = fields.find((f) => ["date", "year", "string"].includes(f.type));
  if (!key) return `${rows.length} rows`;
  const vals = rows.map((r) => r[key.name]).filter(Boolean).sort();
  return `${rows.length} rows · ${key.name} ${vals[0]} → ${vals.at(-1)}`;
}

const NUMERIC = new Set(["number", "integer"]);
// A number-typed column that actually encodes a point in time (e.g.
// `decimal_date`) is an identifier, not a measurement — min/max/mean of it says
// nothing. Skip those; keep genuine measurements like `mlo_ppm_per_year`.
const TIME_KEYS = new Set(["decimal_date", "date", "year", "month", "day", "decade"]);
const isMeasurement = (f: Field) =>
  NUMERIC.has(f.type) && !TIME_KEYS.has(f.name) && !f.name.endsWith("_date");

// --- build the stats block ------------------------------------------------
const block: string[] = [BEGIN, ""];
for (const res of pkg.resources) {
  const rows = readCsv(res.path);
  block.push(`### \`${res.name}\` — ${res.title}`, "", coverage(rows, res.schema.fields), "");
  const numFields = res.schema.fields.filter(isMeasurement);
  if (numFields.length === 0) {
    block.push("_No measurement fields._", "");
    continue;
  }
  block.push(
    "| field | n | missing | min | max | mean | median | std dev |",
    "|---|--:|--:|--:|--:|--:|--:|--:|",
  );
  for (const f of numFields) {
    const s = numericStats(
      f.name,
      rows.map((r) => r[f.name]),
    );
    block.push(
      `| \`${s.field}\` | ${s.n} | ${s.missing} | ${s.min} | ${s.max} | ${s.mean} | ${s.median} | ${s.stddev} |`,
    );
  }
  block.push("");
}
block.push(END);
const statsBlock = block.join("\n");

// --- splice it into SUMMARY.md ------------------------------------------------
const SUMMARY = join(HERE, "SUMMARY.md");
let doc: string;
if (existsSync(SUMMARY)) {
  const current = readFileSync(SUMMARY, "utf8");
  const b = current.indexOf(BEGIN);
  const e = current.indexOf(END);
  if (b === -1 || e === -1) throw new Error("SUMMARY.md is missing the STATS markers");
  doc = current.slice(0, b) + statsBlock + current.slice(e + END.length);
} else {
  doc = [
    "# Summary — co2-ppm",
    "",
    "Descriptive statistics for every resource. The table block below is generated by [`enrich.ts`](enrich.ts) (`node enrich.ts`) and rewritten in place on each run; the prose around it is written by hand.",
    "",
    "## Statistics",
    "",
    statsBlock,
    "",
    "## What stands out",
    "",
    "_TODO — the handful of things a reader should take from the numbers above._",
    "",
    "## See also",
    "",
    "- _TODO — the story, the source, related datasets._",
    "",
  ].join("\n");
}
writeFileSync(SUMMARY, doc.replace(/\n{3,}/g, "\n\n").replace(/\n*$/, "\n"));
console.log(existsSync(SUMMARY) ? "updated SUMMARY.md stats block" : "wrote SUMMARY.md");
