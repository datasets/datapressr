#!/usr/bin/env python3
"""Build skills/story/references/comparatron-fonts.mjs: the comparatron's serif, embedded.

The comparatron figures are shown on the blog as <img src="...svg">, which cannot load a page's
web fonts, so compare() embeds its face in each SVG as a data URI. This takes Lora 3.008 (SIL Open
Font License 1.1, The Lora Project Authors; Google Fonts ofl/lora), instances the variable font at
400, 500 and 600 (and italic 400), subsets it to printable ASCII plus a few symbols, and writes the
woff2 data and per-glyph advance widths (for measuring text) to one ES module.

Lora has the Reserved Font Name "Lora", and a subset is a Modified Version under the OFL, so the
subset is renamed "Comparatron Serif". The licence travels as comparatron-fonts.OFL.txt.

  python3 -m venv /tmp/ft && /tmp/ft/bin/pip install fonttools brotli
  curl -LO 'https://github.com/google/fonts/raw/main/ofl/lora/Lora%5Bwght%5D.ttf'
  curl -LO 'https://github.com/google/fonts/raw/main/ofl/lora/Lora-Italic%5Bwght%5D.ttf'
  /tmp/ft/bin/python scripts/make-comparatron-fonts.py 'Lora[wght].ttf' 'Lora-Italic[wght].ttf'
"""
import base64, io, json, sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

FAMILY = "Comparatron Serif"
CHARS = "".join(chr(c) for c in range(0x20, 0x7F)) + "\u00a0×–—‘’“”…·•€£°½¼¾²³±≈→←↑↓"
OUT = Path(__file__).resolve().parent.parent / "skills" / "story" / "references" / "comparatron-fonts.mjs"


def build(src, weight, key):
    f = instancer.instantiateVariableFont(TTFont(src), {"wght": weight})
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["kern", "liga", "lnum", "pnum"]
    opts.name_IDs = ["*"]
    opts.hinting = False
    s = subset.Subsetter(opts)
    s.populate(text=CHARS)
    s.subset(f)
    for rec in f["name"].names:
        if rec.nameID in (1, 16):
            rec.string = FAMILY
        elif rec.nameID == 4:
            rec.string = f"{FAMILY} {key}"
        elif rec.nameID in (3, 6):
            rec.string = f"ComparatronSerif-{key}"
    upm, cmap, hmtx = f["head"].unitsPerEm, f.getBestCmap(), f["hmtx"]
    advance = {ch: round(hmtx[cmap[ord(ch)]][0] / upm, 4) for ch in CHARS if ord(ch) in cmap}
    buf = io.BytesIO()
    f.flavor = "woff2"
    f.save(buf)
    return base64.b64encode(buf.getvalue()).decode(), advance


def main(roman, italic):
    faces, advance = {}, {}
    for key, src, w in [("400", roman, 400), ("500", roman, 500), ("600", roman, 600), ("400i", italic, 400)]:
        faces[key], advance[key] = build(src, w, key)
    OUT.write_text(
        "// Generated by scripts/make-comparatron-fonts.py: do not edit.\n"
        "// Comparatron Serif: Lora 3.008 (c) The Lora Project Authors, SIL Open Font License 1.1\n"
        "// (comparatron-fonts.OFL.txt), instanced at 400/500/600 and italic 400, subset to ASCII plus\n"
        "// a few symbols, and renamed as the OFL's Reserved Font Name requires of a modified version.\n"
        f"export const FONTS = {{ family: {json.dumps(FAMILY)}, source: \"Lora 3.008, SIL OFL 1.1\",\n"
        f"  advance: {json.dumps(advance)},\n"
        "  woff2: {\n" + "".join(f"    {json.dumps(k)}: {json.dumps(v)},\n" for k, v in faces.items()) + "  },\n};\n"
    )
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main(*sys.argv[1:3])
